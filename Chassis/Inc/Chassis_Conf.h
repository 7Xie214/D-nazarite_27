/** @brief 底盘配置：直接在本文件修改参数。 */
#ifndef CHASSIS_CONF_H
#define CHASSIS_CONF_H

/* 只能选中一种底盘，也允许全部关闭。麦轮/全向轮目前仅预留初始化分支。 */
#define CHASSIS_ENABLE_MECANUM 0
#define CHASSIS_ENABLE_OMNIWHEEL 0
#define CHASSIS_ENABLE_SWERVE 1

#if (CHASSIS_ENABLE_MECANUM + CHASSIS_ENABLE_OMNIWHEEL + CHASSIS_ENABLE_SWERVE) > 1
#error "At most one CHASSIS_ENABLE_ flag may be enabled."
#endif

#if CHASSIS_ENABLE_SWERVE

/* 单位 m：轮子半径、纵向半轴距、横向半轮距，按实测值填写。 */
#define CHASSIS_SWERVE_WHEEL_RADIUS_M 0.0f
#define CHASSIS_SWERVE_HALF_WHEEL_BASE_M 0.0f
#define CHASSIS_SWERVE_HALF_TRACK_WIDTH_M 0.0f
#define CHASSIS_SWERVE_MAX_WHEEL_SPEED_MPS 0.0f /* Fill with measured safe wheel speed. */

/* Motor rotor turns, before gearbox reduction. User must fill travel. */
#define CHASSIS_FRONT_LEFT_MOVE_ROTOR_TURNS 0.0f
#define CHASSIS_FRONT_RIGHT_MOVE_ROTOR_TURNS 0.0f
/* Software arrival defaults in output-shaft units; not hardware calibration. */
#define CHASSIS_FRONT_MOVE_POS_TOL_RAD 0.01f
#define CHASSIS_FRONT_MOVE_SPEED_TOL_RAD_S 0.05f
#define CHASSIS_FRONT_MOVE_SETTLE_S 0.02f

/* FL/FR/RL/RR：左前、右前、左后、右后。
 * 零偏为原始编码器计数；方向系数为 +1/-1。
 * INITIAL_ANGLE_RAD 为软件初始舵角/保持角，单位 rad。 */

/* 左前轮组 */
#define CHASSIS_SWERVE_FL_ZERO_OFFSET 0u
#define CHASSIS_SWERVE_FL_STEER_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_FL_STEER_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_FL_DRIVE_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_FL_DRIVE_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_FL_ANGLE_RANGE SWERVE_ANGLE_MINUS_90_TO_90
#define CHASSIS_SWERVE_FL_INITIAL_ANGLE_RAD 0.0f

/* 右前轮组 */
#define CHASSIS_SWERVE_FR_ZERO_OFFSET 0u
#define CHASSIS_SWERVE_FR_STEER_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_FR_STEER_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_FR_DRIVE_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_FR_DRIVE_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_FR_ANGLE_RANGE SWERVE_ANGLE_MINUS_90_TO_90
#define CHASSIS_SWERVE_FR_INITIAL_ANGLE_RAD 0.0f

/* 左后轮组 */
#define CHASSIS_SWERVE_RL_ZERO_OFFSET 0u
#define CHASSIS_SWERVE_RL_STEER_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_RL_STEER_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_RL_DRIVE_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_RL_DRIVE_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_RL_ANGLE_RANGE SWERVE_ANGLE_MINUS_90_TO_90
#define CHASSIS_SWERVE_RL_INITIAL_ANGLE_RAD 0.0f

/* 右后轮组 */
#define CHASSIS_SWERVE_RR_ZERO_OFFSET 0u
#define CHASSIS_SWERVE_RR_STEER_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_RR_STEER_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_RR_DRIVE_ENCODER_DIRECTION 1
#define CHASSIS_SWERVE_RR_DRIVE_ELECTRIC_DIRECTION 1
#define CHASSIS_SWERVE_RR_ANGLE_RANGE SWERVE_ANGLE_MINUS_90_TO_90
#define CHASSIS_SWERVE_RR_INITIAL_ANGLE_RAD 0.0f

#endif /* CHASSIS_ENABLE_SWERVE */
#endif /* CHASSIS_CONF_H */
