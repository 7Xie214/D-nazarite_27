/**
 * 梯形速度规划器 —— 位置环的「指令器」。
 *
 * 它不控制任何东西，只回答一个问题：**这一拍，我应该在哪儿、跑多快。**
 * 输出 (pos_ref, vel_ref) 喂给位置环：pos_ref 当设定值，vel_ref 当前馈。
 *
 *   目标位置 ──►[规划器]──► pos_ref ──► ⊖ ──►[位置环 PI]──┐
 *                            vel_ref ─────────────────────►⊕──► 速度环设定值
 *                                          ▲               │
 *                                       实际位置            └─ 前馈
 *
 * ---------------------------------------------------------------------------
 * 为什么位置环外面要套这一层，而不是把目标值直接砸给 PID：
 *
 *   直接砸 = 阶跃给定。想让响应快就得把 Kp 拉大，拉大就振 —— 因为反馈里
 *   没有速度信息，没人负责刹车。把速度规划放进【参考】里之后，参考自己
 *   知道"我在加速段 / 我在减速段"，控制器只剩修残差，Kp 可以压得很小。
 *
 *   顺带一个好处：误差全程都很小，积分饱和这个老问题基本自然消失。
 *
 * ---------------------------------------------------------------------------
 * 核心只有一行 —— 不需要加速/巡航/减速三段状态机：
 *
 *     v_des = min(v_max, sqrt(2 · a_max · |剩余距离|))
 *
 * "当前速度不能超过刹得住的速度"。离得远，根号项大于 v_max，自动顶到
 * v_max（加速完进巡航）；快到了，根号项掉下来，自动变成匀减速。三段是
 * 这个公式的【结果】，不是要写的分支。再套一层加速度限幅（dv ≤ a·dt）
 * 就得到完整的梯形曲线。
 *
 * 因为每拍都从当前位置重算，这个形式天然自纠错：中途改了目标、被打断、
 * 参数不对，下一拍就自己修正回来了，不会积累偏差。
 *
 * 单位：位置和速度用同一套（推荐输出轴弧度 rad / rad/s，和 DjiMotor 的
 * angle_rad / speed_rad_s 对齐），a_max 就是 rad/s²。
 * ---------------------------------------------------------------------------
 */

#ifndef TRAJ_H
#define TRAJ_H

#include <stdint.h>
#include <stddef.h>     /* NULL */

/* 到位判据：位置进到这个范围内，且速度低到一拍就能停下，就认为到了。
 * 1e-4 rad 在输出轴上是 0.006°，比回差小得多，够用。 */
#define TRAJ_POS_EPS   1.0e-4f

typedef struct {
    float   v_max;      /* 巡航速度上限（位置单位/秒） */
    float   a_max;      /* 加速度上限（位置单位/秒²）。必须 > 0 */
    float   pos_ref;    /* 本拍参考位置 —— 喂位置环的设定值 */
    float   vel_ref;    /* 本拍参考速度 —— 喂位置环的前馈 */
    float   target;     /* 目标位置 */
    uint8_t active;     /* 0 = 停着；1 = 正在走 */
} Traj_t;

/* 初始化（设定限幅）。必须 v_max > 0、a_max > 0，否则规划器不动。 */
void Traj_Init(Traj_t *t, float v_max, float a_max);

/* 起一段行程：从 from 走到 to。
 * 内部把 pos_ref 对齐到 from —— 第一拍不会产生位置跳变（参考跳变 = 误差
 * 阶跃，正是这一层要避免的东西）。所以 from 要传【当前位置】。 */
void Traj_Start(Traj_t *t, float from, float to);

/* 立刻停下：清 active，参考速度归零。pos_ref 留在原地，
 * 位置环会在这里稳住（保持当前位置）。 */
void Traj_Stop(Traj_t *t);

/* 推进一拍。停着的时候调用无副作用。dt <= 0 直接忽略。 */
void Traj_Update(Traj_t *t, float dt);

/* 还在走返回 1，到了/停了返回 0。 */
int  Traj_IsActive(const Traj_t *t);

#endif /* TRAJ_H */
